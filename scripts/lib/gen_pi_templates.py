#!/usr/bin/env python3
"""Generate the pi package (role prompt templates) from grok/agents + pi config.

Reads the 20 profiles in ``grok/agents/*.md``, the hand-authored adapter
preamble (``pi/adapter-preamble.md``) and ``pi/port-config.json``, and writes a
pi package to ``build/pi/``:

    package.json          manifest (no timestamps: the output is idempotent)
    prompts/<role>.md     one prompt template per profile, plus ``roster.md``
    PARITY.md             audit hits + dispositions, shipped with the package

Each template is the adapter preamble, a model note derived from the source
frontmatter, and the source body copied byte-verbatim (frontmatter stripped).

Usage:
    gen_pi_templates.py [<out_dir>] [options]

    out_dir                 output directory (default: <repo>/build/pi)
    --repo-root PATH        repository root (default: two levels above this file)
    --src DIR               source profile directory (default: <repo>/grok/agents)
    --config PATH           port config (default: <repo>/pi/port-config.json)
    --preamble PATH         adapter preamble (default: <repo>/pi/adapter-preamble.md)
    --audit                 print the audit hit list as JSON and exit
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT_DEFAULT = Path(__file__).resolve().parents[2]
FRONTMATTER = re.compile(r"^---\r?\n(.*?)\r?\n---\r?\n", re.DOTALL)
MARKER = "<!-- generated by scripts/lib/gen_pi_templates.py; DO NOT EDIT -->"
ROSTER_TITLE = "pi role roster"
ROSTER_DESCRIPTION = "List the role templates in this pi package with argument hints and model notes."


def yaml_quote(value: str) -> str:
    """Return a safe double-quoted YAML scalar."""
    return json.dumps(value, ensure_ascii=False)


def parse_frontmatter(text: str) -> dict[str, str]:
    """Parse the simple ``key: value`` frontmatter used by grok profiles."""
    match = FRONTMATTER.match(text)
    if not match:
        return {}
    fields: dict[str, str] = {}
    for line in match.group(1).splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        fields[key.strip()] = value
    return fields


def split_source(text: str) -> tuple[dict[str, str], str]:
    """Return ``(frontmatter, body)``; the body is preserved byte-verbatim."""
    match = FRONTMATTER.match(text)
    if not match:
        return {}, text
    return parse_frontmatter(text), text[match.end():]


def load_sources(src_dir: Path) -> list[dict[str, object]]:
    """Load every profile, sorted by role name."""
    profiles: list[dict[str, object]] = []
    for path in sorted(src_dir.glob("*.md")):
        meta, body = split_source(path.read_text(encoding="utf-8"))
        name = meta.get("name") or path.stem
        if not meta.get("description"):
            raise SystemExit(f"  [error] {path} has no description in frontmatter")
        profiles.append({"name": name, "meta": meta, "body": body, "path": path})
    if not profiles:
        raise SystemExit(f"  [error] no profiles found in {src_dir}")
    profiles.sort(key=lambda item: str(item["name"]))
    return profiles


def model_note(config: dict, model: str) -> str:
    """Return the pi model note for a source frontmatter model id."""
    notes = config.get("model_notes") or {}
    entry = notes.get(model) or notes.get("default")
    if isinstance(entry, dict):
        text = str(entry.get("text", ""))
    else:
        text = str(entry or "")
    return text.replace("{model}", model)


def model_roster_label(config: dict, model: str) -> str:
    """Return the short roster label for a source frontmatter model id."""
    notes = config.get("model_notes") or {}
    entry = notes.get(model) or notes.get("default")
    if isinstance(entry, dict) and entry.get("roster"):
        return str(entry["roster"])
    return "verify live"


def render_role(
    profile: dict[str, object],
    config: dict,
    preamble: str,
    hint: str,
) -> str:
    """Render one role template: preamble, model note, verbatim body, Task."""
    meta = profile["meta"]
    description = f"{meta.get('description', '')} (pi port)"
    note = model_note(config, str(meta.get("model", "")))
    body = str(profile["body"])
    return (
        "---\n"
        f"description: {yaml_quote(description)}\n"
        f"argument-hint: {yaml_quote(hint)}\n"
        "---\n"
        f"{MARKER}\n\n"
        f"{preamble}\n\n"
        f"**Model note:** {note}\n\n"
        f"{body}"
        "\n## Task\n\n$ARGUMENTS\n"
    )


def render_roster(profiles: list[dict[str, object]], config: dict, preamble: str) -> str:
    """Render the generated ``/roster`` template."""
    roles = config.get("roles") or {}
    hint = str((config.get("roster") or {}).get("argument-hint", "[role filter]"))
    lines = [
        "---",
        f"description: {yaml_quote(ROSTER_DESCRIPTION)}",
        f"argument-hint: {yaml_quote(hint)}",
        "---",
        f"{MARKER}",
        "",
        f"{preamble}",
        "",
        f"# {ROSTER_TITLE}",
        "",
        f"This package ports {len(profiles)} role templates from `grok/agents/`. Invoke one as "
        "`/role <brief>`; the brief text becomes that role's `## Task` body.",
        "",
        "| Role | Argument hint | Source model | Model note |",
        "|---|---|---|---|",
    ]
    for profile in profiles:
        name = str(profile["name"])
        meta = profile["meta"]
        role_hint = str((roles.get(name) or {}).get("argument-hint", "<brief>"))
        model = str(meta.get("model", ""))
        lines.append(
            f"| `/{name}` | {role_hint} | {model} | {model_roster_label(config, model)} |"
        )
    lines.extend(
        [
            "",
            "If the arguments are non-empty, list only the rows that match them by role name "
            "or keyword.",
            "",
            "## Task",
            "",
            "$ARGUMENTS",
            "",
        ]
    )
    return "\n".join(lines)


def audit_hits(config: dict, profiles: list[dict[str, object]]) -> list[dict[str, object]]:
    """Return one hit per (construct, profile) that mentions a lexicon term."""
    hits: list[dict[str, object]] = []
    constructs = (config.get("audit") or {}).get("constructs") or []
    for construct in constructs:
        terms = [str(term).lower() for term in construct.get("terms") or []]
        overrides = construct.get("overrides") or {}
        for profile in profiles:
            name = str(profile["name"])
            body = str(profile["body"]).lower()
            matched = sorted({term for term in terms if term in body})
            if not matched:
                continue
            hits.append(
                {
                    "construct": str(construct["id"]),
                    "profile": name,
                    "terms": matched,
                    "disposition": str(overrides.get(name, construct.get("disposition", ""))),
                }
            )
    hits.sort(key=lambda hit: (str(hit["construct"]), str(hit["profile"])))
    return hits


def render_parity(config: dict, hits: list[dict[str, object]]) -> str:
    """Render PARITY.md: dispositions plus the construct x profile hit table."""
    constructs = (config.get("audit") or {}).get("constructs") or []
    lines = [
        "# pi parity",
        "",
        f"{MARKER}",
        "",
        "Every harness-specific construct found in `grok/agents/` and how the pi port "
        "handles it. Bodies are copied verbatim; all adaptation lives in the shared "
        "adapter preamble (`pi/adapter-preamble.md`).",
        "",
        "## Constructs",
        "",
        "| Construct | What it is | Disposition | Rationale |",
        "|---|---|---|---|",
    ]
    for construct in constructs:
        lines.append(
            f"| {construct['id']} | {construct.get('label', '')} | "
            f"{construct.get('disposition', '')} | {construct.get('rationale', '')} |"
        )
    lines.extend(
        [
            "",
            "## Hits (construct x profile)",
            "",
            "| Construct | Profile | Disposition |",
            "|---|---|---|",
        ]
    )
    for hit in hits:
        lines.append(
            f"| {hit['construct']} | {hit['profile']} | {hit['disposition']} |"
        )
    lines.extend(
        [
            "",
            f"{len(hits)} hit(s) across {len(constructs)} construct(s).",
            "",
        ]
    )
    return "\n".join(lines)


def ensure_trailing_newline(text: str) -> str:
    return text if text.endswith("\n") else text + "\n"


def package_manifest(config: dict) -> dict[str, object]:
    """Return the deterministic package.json payload."""
    package = config.get("package") or {}
    return {
        "name": str(package.get("name", "open-agent-definitions-pi")),
        "version": str(package.get("version", "1.0.0")),
        "description": str(package.get("description", "")),
        "license": str(package.get("license", "Unlicense")),
        "keywords": list(package.get("keywords") or ["pi-package"]),
    }


def build_package(
    config: dict,
    profiles: list[dict[str, object]],
    preamble: str,
) -> dict[str, str]:
    """Return ``{relative path: file text}`` for the whole package."""
    roles = config.get("roles") or {}
    files: dict[str, str] = {
        "package.json": ensure_trailing_newline(
            json.dumps(package_manifest(config), indent=2, ensure_ascii=False)
        ),
        "PARITY.md": render_parity(config, audit_hits(config, profiles)),
    }
    for profile in profiles:
        name = str(profile["name"])
        hint = str((roles.get(name) or {}).get("argument-hint", "<brief>"))
        files[f"prompts/{name}.md"] = render_role(profile, config, preamble, hint)
    files["prompts/roster.md"] = render_roster(profiles, config, preamble)
    return files


def write_package(out_dir: Path, files: dict[str, str]) -> None:
    """Write a package tree, removing stale prompt templates first."""
    prompts_dir = out_dir / "prompts"
    if prompts_dir.is_dir():
        for stale in prompts_dir.glob("*.md"):
            stale.unlink()
    prompts_dir.mkdir(parents=True, exist_ok=True)
    for rel_path, text in sorted(files.items()):
        target = out_dir / rel_path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def load_config(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def resolve_paths(args: argparse.Namespace) -> tuple[dict, Path, Path, Path]:
    repo_root = Path(args.repo_root).resolve() if args.repo_root else REPO_ROOT_DEFAULT
    config_path = (
        Path(args.config).resolve() if args.config else repo_root / "pi" / "port-config.json"
    )
    preamble_path = (
        Path(args.preamble).resolve()
        if args.preamble
        else repo_root / "pi" / "adapter-preamble.md"
    )
    config = load_config(config_path)
    source = config.get("source") or {}
    src_dir = (
        Path(args.src).resolve()
        if args.src
        else repo_root / str(source.get("agents_dir", "grok/agents"))
    )
    out_dir = Path(args.out_dir).resolve() if args.out_dir else repo_root / "build" / "pi"
    return config, preamble_path, src_dir, out_dir


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gen_pi_templates.py",
        description="Generate the pi package from grok/agents profiles.",
    )
    parser.add_argument("out_dir", nargs="?", default=None, help="output directory (default: build/pi)")
    parser.add_argument("--out", dest="out_opt", default=None, help="output directory (same as the positional)")
    parser.add_argument("--repo-root", default=None, help="repository root")
    parser.add_argument("--src", default=None, help="source profile directory")
    parser.add_argument("--config", default=None, help="port config path")
    parser.add_argument("--preamble", default=None, help="adapter preamble path")
    parser.add_argument(
        "--audit",
        action="store_true",
        help="print the audit hit list as JSON and exit",
    )
    args = parser.parse_args(argv)
    args.out_dir = args.out_opt or args.out_dir

    config, preamble_path, src_dir, out_dir = resolve_paths(args)
    profiles = load_sources(src_dir)
    if args.audit:
        hits = audit_hits(config, profiles)
        payload = {
            "constructs": [
                {
                    "id": construct["id"],
                    "disposition": construct.get("disposition", ""),
                }
                for construct in (config.get("audit") or {}).get("constructs") or []
            ],
            "hits": hits,
            "count": len(hits),
        }
        print(json.dumps(payload, indent=2, sort_keys=True))
        return 0

    if not preamble_path.is_file():
        print(f"  [error] missing adapter preamble: {preamble_path}", file=sys.stderr)
        return 1
    preamble = preamble_path.read_text(encoding="utf-8").strip("\n")

    files = build_package(config, profiles, preamble)
    write_package(out_dir, files)
    prompt_count = len([rel for rel in files if rel.startswith("prompts/")])
    print(f"  [ok]    generated pi package: {prompt_count} template(s) -> {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
