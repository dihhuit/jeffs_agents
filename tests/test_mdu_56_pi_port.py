#!/usr/bin/env python3
"""MDU-56 gates: the generated pi package must stay a faithful port of grok/agents.

Design: ``docs/design/mdu-56-pi-port.md`` D4. Five gates:

- **A (shape)**      20 sources -> 21 templates (20 roles + roster); filenames are
                     source ``name`` frontmatter values; every frontmatter parses
                     with non-empty ``description``/``argument-hint``; descriptions
                     are the source description plus ``" (pi port)"``.
- **B (verbatim body)** each template ends with the source body bytes + the fixed
                     ``## Task`` tail; no prose drift, no normalisation.
- **C (golden/idempotency)** two independent generations are byte-identical to each
                     other *and* to ``tests/fixtures/pi_golden/``, so an
                     unregenerated ``grok/agents`` or ``pi/`` edit reds the suite.
- **D (parity coverage)** every ``--audit`` hit (construct x profile) has a row in
                     ``docs/pi-parity.md``; the audit fails closed (nonzero + captured
                     error text) on an empty sources dir.
- **E (preamble)**    every template carries the five adapter-preamble clause
                     headings and the precedence sentence.

The generator is driven as a subprocess (``sys.executable``), matching the repo
convention for lib scripts and exercising the real CLI. All generation targets are
``tmp_path``; ``build/`` is never written from the tests.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
GENERATOR = REPO / "scripts" / "lib" / "gen_pi_templates.py"
SRC_DIR = REPO / "grok" / "agents"
GOLDEN = REPO / "tests" / "fixtures" / "pi_golden"
PARITY = REPO / "docs" / "pi-parity.md"
CONFIG = REPO / "pi" / "port-config.json"
PREAMBLE = REPO / "pi" / "adapter-preamble.md"

FRONTMATTER = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n", re.DOTALL)
PORT_SUFFIX = " (pi port)"
TASK_TAIL = b"\n## Task\n\n$ARGUMENTS\n"
MARKER = "<!-- generated by scripts/lib/gen_pi_templates.py; DO NOT EDIT -->"

#: Pinned adapter-preamble headings (Gate E). Renaming one is a deliberate design
#: change and must be mirrored here, exactly as written in pi/adapter-preamble.md.
PREAMBLE_HEADINGS = (
    "## 1. Harness delta",
    "## 2. Delegation reframe",
    "## 3. Inert mechanics",
    "## 4. MCP tools",
    "## 5. Harness-agnostic clauses that stand",
)
PRECEDENCE = (
    "**This preamble overrides conflicting harness-specific instructions in the body.**"
)

SOURCE_PATHS = sorted(SRC_DIR.glob("*.md"))


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _run(*args: str, cwd: Path | None = None) -> subprocess.CompletedProcess:
    """Run the generator CLI; captured text so failures can print real output."""
    return subprocess.run(
        [sys.executable, str(GENERATOR), *args],
        capture_output=True,
        text=True,
        cwd=str(cwd or REPO),
        timeout=120,
    )


def _split(text: str) -> tuple[dict[str, str], str]:
    """Independently parse frontmatter, returning ``(fields, body)``.

    Duplicated on purpose: Gate A/B must not trust the generator's own parser.
    """
    match = FRONTMATTER.match(text)
    assert match is not None, "source profile has no frontmatter"
    fields: dict[str, str] = {}
    for line in match.group(1).splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        fields[key.strip()] = value
    return fields, text[match.end():]


def _source(role: str) -> tuple[dict[str, str], str]:
    return _split((SRC_DIR / f"{role}.md").read_text(encoding="utf-8"))


def _tree(root: Path) -> dict[str, bytes]:
    """Map relative path -> bytes for every file under ``root``."""
    return {
        str(path.relative_to(root)): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


def _generate(out_dir: Path, *extra: str) -> dict[str, bytes]:
    proc = _run(str(out_dir), *extra)
    assert proc.returncode == 0, (
        f"generator failed (rc={proc.returncode})\nstdout:\n{proc.stdout}\n"
        f"stderr:\n{proc.stderr}"
    )
    files = _tree(out_dir)
    assert files, f"generator wrote nothing into {out_dir}"
    return files


def _diff(expected: dict[str, bytes], actual: dict[str, bytes]) -> str:
    """Human-readable description of the tree difference."""
    missing = sorted(set(expected) - set(actual))
    extra = sorted(set(actual) - set(expected))
    changed = sorted(
        key for key in set(expected) & set(actual) if expected[key] != actual[key]
    )
    return (
        f"missing={missing}\nextra={extra}\n"
        f"changed={[(key, len(expected[key]), len(actual[key])) for key in changed]}"
    )


@pytest.fixture(scope="session")
def generated(tmp_path_factory: pytest.TempPathFactory) -> dict[str, bytes]:
    """One generation shared by the read-only gates."""
    return _generate(tmp_path_factory.mktemp("pi-gen"))


@pytest.fixture(scope="session")
def roles() -> list[str]:
    names = []
    for path in SOURCE_PATHS:
        fields, _ = _split(path.read_text(encoding="utf-8"))
        names.append(fields.get("name") or path.stem)
    return names


