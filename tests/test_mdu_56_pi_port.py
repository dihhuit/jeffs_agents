def test_gate_e_preamble_file_pins_the_clauses():
    preamble = PREAMBLE.read_text(encoding="utf-8")
    assert len(PREAMBLE_HEADINGS) == 5
    missing = [heading for heading in PREAMBLE_HEADINGS if heading not in preamble]
    assert not missing, f"pi/adapter-preamble.md lost headings: {missing}"
    assert PRECEDENCE in preamble, "precedence sentence missing from the preamble"


def test_gate_e_every_template_carries_the_preamble(generated):
    preamble = PREAMBLE.read_text(encoding="utf-8").strip("\n").encode("utf-8")
    problems = []
    for key in sorted(generated):
        if not (key.startswith("prompts/") and key.endswith(".md")):
            continue
        template = generated[key]
        if preamble not in template:
            problems.append(f"{key}: preamble block missing or altered")
        for heading in PREAMBLE_HEADINGS:
            if heading.encode("utf-8") not in template:
                problems.append(f"{key}: missing heading {heading!r}")
        if PRECEDENCE.encode("utf-8") not in template:
            problems.append(f"{key}: missing precedence sentence")
        if not template.startswith(b"---\n") or MARKER.encode() not in template:
            problems.append(f"{key}: frontmatter/marker ordering")
        # Preamble precedes the body: heading 1 comes before the model note.
        note_at = template.find(b"**Model note:**")
        if note_at >= 0 and template.find(PREAMBLE_HEADINGS[0].encode()) > note_at:
            problems.append(f"{key}: preamble is not before the model note")
    assert not problems, "\n".join(problems)
