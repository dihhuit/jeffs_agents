def test_gate_a_twenty_sources_to_twenty_one_templates(generated, roles):
    assert len(SOURCE_PATHS) == 20, [p.name for p in SOURCE_PATHS]
    assert len(set(roles)) == 20, roles

    prompt_files = sorted(
        key[len("prompts/"):]
        for key in generated
        if key.startswith("prompts/") and key.endswith(".md")
    )
    assert len(prompt_files) == 21, f"expected 20 roles + roster, got {prompt_files}"
    assert prompt_files == sorted([f"{role}.md" for role in roles] + ["roster.md"]), (
        prompt_files
    )
    # Filenames are the source ``name`` values, not the source filenames.
    for role, source in zip(roles, SOURCE_PATHS):
        assert f"prompts/{role}.md" in generated
        assert source.stem == role, f"{source.name} declares name {role!r}"
    assert generated["prompts/roster.md"]


def test_gate_a_every_frontmatter_parses_with_required_keys(generated):
    problems = []
    for key, payload in sorted(generated.items()):
        if not (key.startswith("prompts/") and key.endswith(".md")):
            continue
        text = payload.decode("utf-8")
        match = FRONTMATTER.match(text)
        if match is None:
            problems.append(f"{key}: no frontmatter")
            continue
        fields, _ = _split(text)
        for required in ("description", "argument-hint"):
            if not fields.get(required, "").strip():
                problems.append(f"{key}: missing/empty {required}")
        if not re.search(r"^description: \"", match.group(1), re.MULTILINE):
            problems.append(f"{key}: description is not a quoted scalar")
    assert not problems, "\n".join(problems)


def test_gate_a_descriptions_are_source_plus_port_suffix(generated):
    problems = []
    for role in sorted(p for p in generated if p.startswith("prompts/") and p.endswith(".md")):
        name = role[len("prompts/"):-len(".md")]
        fields, _ = _split(generated[role].decode("utf-8"))
        if name == "roster":
            if not fields.get("description", "").strip():
                problems.append("roster: empty description")
            continue
        source_fields, _ = _source(name)
        expected = source_fields.get("description", "") + PORT_SUFFIX
        if fields.get("description") != expected:
            problems.append(f"{name}: {fields.get('description')!r} != {expected!r}")
        elif not expected.endswith(" (pi port)"):
            problems.append(f"{name}: unexpected suffix spacing in {expected!r}")
    assert not problems, "\n".join(problems)


def test_gate_a_argument_hints_come_from_port_config(generated):
    config = json.loads(CONFIG.read_text(encoding="utf-8"))
    problems = []
    for role, spec in sorted((config.get("roles") or {}).items()):
        fields, _ = _split(generated[f"prompts/{role}.md"].decode("utf-8"))
        expected = str(spec.get("argument-hint", ""))
        if fields.get("argument-hint") != expected:
            problems.append(f"{role}: {fields.get('argument-hint')!r} != {expected!r}")
    roster_fields, _ = _split(generated["prompts/roster.md"].decode("utf-8"))
    expected_roster = str((config.get("roster") or {}).get("argument-hint", ""))
    if roster_fields.get("argument-hint") != expected_roster:
        problems.append(f"roster: {roster_fields.get('argument-hint')!r} != {expected_roster!r}")
    assert len(config.get("roles") or {}) == 20
    assert not problems, "\n".join(problems)


