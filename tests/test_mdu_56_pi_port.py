def test_gate_d_every_audit_hit_has_a_parity_row():
    proc = _run("--audit")
    assert proc.returncode == 0, f"audit failed: {proc.stderr}"
    payload = json.loads(proc.stdout)

    hits = payload["hits"]
    assert payload["count"] == len(hits)
    assert hits, "audit found no hits — Gate D would be vacuous"
    assert {hit["construct"] for hit in hits} >= {
        "delegation",
        "mcp-playwright",
        "model-tables",
    }, sorted({hit["construct"] for hit in hits})
    for hit in hits:
        assert hit["terms"], f"{hit['construct']}/{hit['profile']}: no matched terms"

    rows: dict[tuple[str, str], str] = {}
    for line in PARITY.read_text(encoding="utf-8").splitlines():
        match = re.match(
            r"^\|\s*([a-z0-9-]+)\s*\|\s*([a-z0-9-]+)\s*\|\s*([^|]+?)\s*\|\s*$", line
        )
        if match and match.group(1) not in {"construct", "Construct"}:
            rows[(match.group(1), match.group(2))] = match.group(3).strip()

    missing = [
        (hit["construct"], hit["profile"])
        for hit in hits
        if (hit["construct"], hit["profile"]) not in rows
    ]
    assert not missing, (
        f"audit hits with no row in {PARITY.name}: {missing}\n"
        f"({len(hits)} hits, {len(rows)} rows)"
    )
    mismatched = [
        (hit["construct"], hit["profile"], hit["disposition"], rows[key])
        for hit in hits
        for key in [(hit["construct"], hit["profile"])]
        if rows[key] != hit["disposition"]
    ]
    assert not mismatched, f"parity disposition drift: {mismatched}"


def test_gate_d_shipped_parity_lists_every_hit(generated):
    """The generated PARITY.md ships in the package; it must not miss a hit."""
    shipped = generated["PARITY.md"].decode("utf-8")
    payload = json.loads(_run("--audit").stdout)
    missing = [
        (hit["construct"], hit["profile"])
        for hit in payload["hits"]
        if f"| {hit['construct']} | {hit['profile']} |" not in shipped
    ]
    assert not missing, f"generated PARITY.md missing rows: {missing}"


def test_gate_d_audit_fails_closed_on_empty_sources(tmp_path):
    empty = tmp_path / "empty-src"
    empty.mkdir()
    proc = _run("--src", str(empty), "--audit")
    captured = proc.stdout + proc.stderr
    assert proc.returncode != 0, f"empty sources dir was accepted: {captured!r}"
    assert proc.returncode == 1, f"unexpected exit code {proc.returncode}: {captured!r}"
    assert "no profiles found" in proc.stderr, proc.stderr
    assert str(empty) in proc.stderr, proc.stderr
    assert "hits" not in proc.stdout, f"audit emitted JSON for empty sources: {proc.stdout!r}"


