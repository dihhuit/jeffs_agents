@pytest.mark.parametrize("role", [p.stem for p in SOURCE_PATHS])
def test_gate_b_golden_body_is_byte_verbatim(role):
    """The golden template carries the source body bytes, untouched."""
    source_text = (SRC_DIR / f"{role}.md").read_text(encoding="utf-8")
    fields, body = _split(source_text)
    name = fields.get("name") or role
    template = (GOLDEN / "prompts" / f"{name}.md").read_bytes()

    assert template.endswith(TASK_TAIL), f"{name}: missing Task tail"
    head = template[: -len(TASK_TAIL)]
    body_bytes = body.encode("utf-8")

    # Byte equality of the trailing body segment: the template head must end with
    # exactly the source body, not a normalised or rewritten copy.
    assert len(head) > len(body_bytes), f"{name}: template head has no prefix"
    assert head[-len(body_bytes):] == body_bytes, (
        f"{name}: golden body bytes differ from grok/agents/{role}.md\n"
        f"source tail: {body_bytes[-120:]!r}\n"
        f"template tail: {head[-120:]!r}"
    )
    # Exactly once, so a duplicated body cannot satisfy the tail check.
    assert template.count(body_bytes) == 1, f"{name}: body appears more than once"
    # The Task tail follows the body immediately: no prose injected between them.
    assert template[len(head) - len(body_bytes):] == body_bytes + TASK_TAIL
    # Model note sits between the preamble and the body, exactly once.
    assert template.count(b"**Model note:**") == 1, f"{name}: model note count"
    # Bytes a text normaliser would silently rewrite (em dash, curly quotes,
    # trailing double space) must survive unchanged.
    for token in ("\u2014", "\u2019", "\u201c", "  \n"):
        if token.encode("utf-8") in body_bytes:
            assert token.encode("utf-8") in template, f"{name}: lost {token!r}"


