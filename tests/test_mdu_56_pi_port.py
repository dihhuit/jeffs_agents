def test_gate_c_two_generations_are_byte_identical(tmp_path):
    first = _generate(tmp_path / "one")
    second = _generate(tmp_path / "two")
    assert first.keys() == second.keys(), _diff(first, second)
    assert first == second, _diff(first, second)


def test_gate_c_generation_matches_golden(tmp_path, generated):
    golden = _tree(GOLDEN)
    assert golden, f"golden snapshot missing at {GOLDEN}"
    assert len(golden) == 23, sorted(golden)
    assert generated == golden, (
        "build/pi drifted from tests/fixtures/pi_golden/ — regenerate the golden "
        "deliberately (see pi/README.md refresh checklist):\n" + _diff(golden, generated)
    )


def test_gate_c_out_alias_matches_positional(tmp_path):
    positional = _generate(tmp_path / "positional")
    alias_dir = tmp_path / "alias"
    proc = _run(str(tmp_path / "decoy-must-not-be-used"), "--out", str(alias_dir))
    assert proc.returncode == 0, f"generator failed: {proc.stdout} {proc.stderr}"
    alias = _tree(alias_dir)
    assert positional == alias, _diff(positional, alias)
    assert not (tmp_path / "decoy-must-not-be-used").exists()


def test_gate_c_manifest_is_timestamp_free(generated):
    manifest = json.loads(generated["package.json"].decode("utf-8"))
    assert manifest["name"] == "open-agent-definitions-pi"
    assert manifest["keywords"] == ["pi-package"]
    keys = set(manifest) | {key.lower() for key in manifest}
    assert not {key for key in keys if "time" in key or "date" in key}, sorted(manifest)


